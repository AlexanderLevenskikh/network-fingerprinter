// Browser-level retry contract: real Analyst UI, real multipart endpoint, no mocks.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext();
    const base = 'http://127.0.0.1:3000';
    const response = await context.request.post(base + '/api/auth/login', {
      form: { username: process.env.APP_ADMIN_USERNAME || 'admin', password: process.env.APP_ADMIN_PASSWORD },
    });
    if (response.status() !== 200) throw new Error('Browser authentication failed: ' + response.status());
    const page = await context.newPage();
    await page.goto(base + '/player');
    const chooser = page.locator('input[type="file"]');
    await chooser.waitFor();
    const bad = { name: 'broken.pcap', mimeType: 'application/vnd.tcpdump.pcap', buffer: Buffer.from('not a pcap') };
    await chooser.setInputFiles(bad);
    await page.getByText(/Import failed|Ошибка импорта/).waitFor({ timeout: 30000 });
    if (!(await chooser.isEnabled())) throw new Error('File input was disabled after import error');

    // Reuse the synthetic valid PCAP generated by the smoke test.
    const good = path.join(__dirname, 'browser_retry.pcap');
    await chooser.setInputFiles(good);
    await page.getByText(/Indexed packets: 2|Проиндексировано пакетов: 2/).waitFor({ timeout: 60000 });
    if (!(await chooser.isEnabled())) throw new Error('File input was disabled after retry');
    console.log('PASS browser UI: error -> input enabled -> successful import');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
