// Browser-level retry contract: real Analyst UI, real multipart endpoint, no mocks.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext();
    const base = 'http://127.0.0.1:3000';
    const response = await context.request.post(base + '/api/auth/login', {
      form: { username: process.env.APP_ADMIN_USERNAME || 'admin', password: process.env.APP_ADMIN_PASSWORD },
    });
    if (response.status() !== 200) throw new Error('Browser authentication failed: ' + response.status());
    const page = await context.newPage();
    await page.goto(base + '/player/upload');
    page.on('pageerror', err => console.error('BROWSER_PAGE_ERROR', String(err).slice(0, 500)));
    page.on('response', async r => {
      if (r.url().includes('/api/player/upload')) {
        let body = '';
        try { body = (await r.text()).slice(0, 700); } catch (_) {}
        console.log('BROWSER_UPLOAD_RESPONSE', r.status(), body);
      }
    });
    const chooser = page.locator('input[type="file"]');
    await chooser.waitFor({ state: 'attached' });
    const bad = { name: 'broken.pcap', mimeType: 'application/vnd.tcpdump.pcap', buffer: Buffer.from('not a pcap') };
    const [badResponse] = await Promise.all([
      page.waitForResponse(resp => resp.url().includes('/api/player/upload'), { timeout: 30000 }),
      chooser.setInputFiles(bad),
    ]);
    console.log('Browser invalid upload HTTP status:', badResponse.status());
    if (badResponse.status() < 400 || badResponse.status() >= 500) {
      throw new Error('Browser invalid PCAP must fail with HTTP 4xx');
    }
    try {
      await page.getByText(/Import failed|Ошибка импорта/).waitFor({ timeout: 10000 });
    } catch (error) {
      console.error('Browser URL:', page.url());
      console.error('PCAP results text:', await page.locator('[aria-label="PCAP import results"]').innerText());
      throw error;
    }
    if (!(await chooser.isEnabled())) throw new Error('File input was disabled after import error');

    // Reuse the synthetic valid PCAP generated by the smoke test.
    const good = path.join(__dirname, 'browser_retry.pcap');
    await chooser.setInputFiles(good);
    await page.getByText(/Indexed packets: 2|Проиндексировано пакетов: 2/).waitFor({ timeout: 60000 });
    if (!(await chooser.isEnabled())) throw new Error('File input was disabled after retry');
    const resultsText = await page.locator('[aria-label="PCAP import results"]').innerText();
    if (!resultsText.includes('broken.pcap') || !resultsText.includes('browser_retry.pcap')) {
      throw new Error('The per-file results list lost a previously selected file');
    }

    console.log('PASS browser UI: error -> input enabled -> successful import');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
